interface HandEntry {
  kanji: string
  questions: { sentence: string; reading: string }[]
}

function parseHandSentence(sentence: string, reading: string): QuestionPart[] {
  const parts: QuestionPart[] = []
  const re = /([㐀-鿿]+)\(([ぁ-ゖー]+)\)|○/gu
  let last = 0
  let m: RegExpExecArray | null
  while ((m = re.exec(sentence))) {
    if (m.index > last) parts.push({ text: sentence.slice(last, m.index) })
    if (m[0] === '○') parts.push({ blank: { reading } })
    else parts.push({ text: m[1], ruby: m[2] })
    last = m.index + m[0].length
  }
  if (last < sentence.length) parts.push({ text: sentence.slice(last) })
  return parts
}

